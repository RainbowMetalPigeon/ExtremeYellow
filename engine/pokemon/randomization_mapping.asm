; input : d = original mon id
; output: d = randomized mon id
ReplacePokemonWithRandom::
; choose the intended list from the first random value
	ld hl, ListOfMappingLists
	ld a, [wRandomizationWildEncounters_R1_List]
	add a ; because they're addresses, 2 bytes
	ld c, a
	ld b, 0
	add hl, bc ; we point to the intended list
	ld a, [hli]
	ld h, [hl]
	ld l, a ; hl = intended list
; we got the list, now handle offset
; store the start of the list if we need to wrap
	ld a, h
	ld [wArrayForTemporaryStorage+1], a
	ld a, l
	ld [wArrayForTemporaryStorage+2], a
; add offset
	ld a, [wRandomizationWildEncounters_R2_Offset]
	ld c, a
	ld b, 0
	add hl, bc ; wRandomizationWildEncounters_R2_Offset is not bigger than the list's length itself, so no need to check for carries
	inc d ; we +1 the input mon's ID because we dec it at the beginning of the loop
.speciesLoop
	ld a, [hl]
	cp $FF ; did we reach the end of the list?
	jr nz, .notEndOfList
; let's wrap to beginning
	ld a, [wArrayForTemporaryStorage+1]
	ld h, a
	ld a, [wArrayForTemporaryStorage+2]
	ld l, a
	ld a, [hl]
.notEndOfList
; a holds the (currently pointed) randomized mon; did we advance enough?
	dec d
	jr z, .done
; not yet
	inc hl
	jr .speciesLoop
.done
	ld d, a
	ret

